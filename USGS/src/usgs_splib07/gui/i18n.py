def t(key: str, lang: str = DEFAULT_LANG, **fmt) -> str:
    """Text for ``key`` in ``lang`` (falls back to English); ``fmt`` fills ``{placeholders}``."""
    entry = STRINGS[key]
    text = entry.get(lang) or entry[DEFAULT_LANG]
    return text.format(**fmt) if fmt else text
