def _name(fn: Callable) -> str:
    owner = fn.__qualname__.split(".")[0] if "." in fn.__qualname__ else ""
    return f"{owner}.{fn.__name__}" if owner else fn.__name__


def _signature(fn: Callable) -> str:
    """Parameter names with short defaults, e.g. ``(home=None, chapters='MS', ...)`` (annotations omitted)."""
    parts = []
    for n, p in inspect.signature(fn).parameters.items():
        if n in ("self", "cls"):
            continue
        if p.kind is p.VAR_KEYWORD:
            parts.append("**" + n)
        elif p.kind is p.VAR_POSITIONAL:
            parts.append("*" + n)
        elif p.default is p.empty:
            parts.append(n)
        else:
            d = repr(p.default)
            parts.append(f"{n}={d if len(d) <= 22 else '...'}")
    return "(" + ", ".join(parts) + ")"


def _summary(fn: Callable) -> str:
    doc = inspect.getdoc(fn) or ""
    text = " ".join(doc.split("\n\n")[0].split())
    return re.sub(r":\w+:`~?([^`]+)`", r"`\1`", text).replace("``", "`")


def list_functions(group: Optional[str] = None) -> pd.DataFrame:
    """Table of every public function: group, name, signature and one-line summary. ``group`` filters by text in the group title."""
    rows: List[dict] = []
    for title, _, fns in GROUPS:
        if group and group.lower() not in title.lower():
            continue
        for fn in fns:
            rows.append({"group": title, "name": _name(fn), "signature": _signature(fn), "summary": _summary(fn)})
    return pd.DataFrame(rows, columns=["group", "name", "signature", "summary"])


def catalogue_markdown(compact: bool = False) -> str:
    """The function catalogue as markdown: full signatures (``docs/FUNCTIONS.md``) or, with ``compact=True``, names only (README)."""
    out = [] if compact else ["# Function catalogue", "",
           "Generated by `splib07 functions --markdown`; do not edit by hand. All wavelengths are in nanometres.", ""]
    df = list_functions()
    h = "###" if compact else "##"
    for title, blurb, _ in GROUPS:
        out += [f"{h} {title}", "", blurb, "", "| Function | What it does |", "|---|---|"]
        for _, r in df[df["group"] == title].iterrows():
            label = r["name"] + "()" if compact else r["name"] + r["signature"]
            out.append(f"| `{label}` | {r['summary'].replace('|', chr(92) + '|')} |")
        out.append("")
    return "\n".join(out)
